const assert=require('node:assert/strict'),fs=require('node:fs');
const E=require('../public/3d/story-state.js'),P=require('../public/3d/prison-dungeons.js'),J=require('../public/3d/journal-clues.js');
const book=JSON.parse(fs.readFileSync('public/3d/story/prison-dungeons.json'));
const state=(time,i,open=false)=>P.pressState(time,i,open);
assert.equal(P.PRESS_Z.length,3);
assert(state(0,0).bottom>130);
assert(state(2.2,0).warning);
assert(state(3,0).down);
assert(!state(3,1).down,'staggered presses leave a different opening');
assert(state(0,0,true).bottom>130&&!state(0,0,true).down,'completed gate stops the machine');
let s=E.create(),serial=0;
const use=key=>{const r=E.transact(s,book,{id:'press-'+ ++serial,type:'world',key});s=r.state;return r.changed;};
assert(!use('kd.press.brake'),'lift gate must be open first');
assert(!use('kd.brace.2')&&!use('kd.latch')&&!use('kd.deep.0'),'retired inputs are inactive');
Object.assign(s.flags,{'kd.lift.open':true});
s.items['kd.brace.mask']=4;s.items['kd.deep.side.0']=1;s.items['kd.deep.side.1']=1;s.items['kd.deep.side.2']=2;
assert(!s.flags['kd.deep.open'],'prior partial values are not a shortcut');
assert(use('kd.press.brake')&&s.flags['kd.deep.open']);
assert(!use('kd.press.brake'),'brake is once only');
assert(P.shards(s).some(q=>q.id==='RK-03'));
const restored=E.restore(s);assert(restored.flags['kd.deep.open']&&P.shards(restored).some(q=>q.id==='RK-03'));
const g={p:{x:-205,z:-2760,y:0},storyObjects:[{key:'kd.press.brake',x:-205,z:-2760,y:0}],storyState:{notes:{'kd.depth':{text:'saved'}}}};
assert.equal(J.related(g),'kd.depth');g.storyState.notes={};assert.equal(J.related(g),null);
console.log('Prison presses passed: distinct phases, warning, stopped save, retired inputs, once-only brake, RK-03 and nearby clue.');
